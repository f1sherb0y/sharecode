# Builds the x86 and x64 meeting helpers from the Tauri client's sources with rustc
# (targets i686-pc-windows-msvc and x86_64-pc-windows-msvc) and embeds them.
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$source = [IO.Path]::GetFullPath((Join-Path $root '../../src-tauri-client/native'))
$out = Join-Path $root 'assets'
New-Item -ItemType Directory -Force $out | Out-Null
$oldHook = $env:MEETING_HOOK_PATH
try {
    foreach ($pair in @(@('x86', 'i686-pc-windows-msvc'), @('x64', 'x86_64-pc-windows-msvc'))) {
        $arch = $pair[0]; $target = $pair[1]
        $dll = Join-Path $out "meeting_hook_$arch.dll"
        & rustc --edition=2021 --crate-type cdylib -C opt-level=s -C panic=abort -C target-feature=+crt-static --target $target (Join-Path $source 'meeting_window_hook.rs') -o $dll
        if ($LASTEXITCODE -ne 0) { throw "Meeting DLL build failed for $target" }
        $env:MEETING_HOOK_PATH = $dll
        & rustc --edition=2021 --crate-type bin -C opt-level=s -C panic=abort -C target-feature=+crt-static --target $target (Join-Path $source 'meeting_window_bridge.rs') -o (Join-Path $out "meeting_bridge_$arch.exe")
        if ($LASTEXITCODE -ne 0) { throw "Meeting bridge build failed for $target" }
    }
} finally { $env:MEETING_HOOK_PATH = $oldHook }
$source = @'
// Code generated by build-helpers.ps1; DO NOT EDIT.

//go:build windows

package nativewin

import _ "embed"

var (
	//go:embed assets/meeting_bridge_x86.exe
	embeddedX86Host []byte
	//go:embed assets/meeting_hook_x86.dll
	embeddedX86DLL []byte
	//go:embed assets/meeting_bridge_x64.exe
	embeddedX64Host []byte
	//go:embed assets/meeting_hook_x64.dll
	embeddedX64DLL []byte
)

func init() {
	DefaultHelperAssets = HelperAssets{embeddedX86Host, embeddedX86DLL, embeddedX64Host, embeddedX64DLL}
}
'@
[IO.File]::WriteAllText((Join-Path $root 'assets_generated_windows.go'), ($source -replace "`r", '') + "`n")
Write-Output 'Built and embedded x86/x64 meeting helpers.'
